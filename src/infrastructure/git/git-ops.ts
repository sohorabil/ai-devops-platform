import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { config } from "@infrastructure/config.js";
import { logger } from "@infrastructure/logger.js";

const execFileAsync = promisify(execFile);

async function git(args: string[], cwd: string): Promise<string> {
  const { stdout } = await execFileAsync("git", args, { cwd });
  return stdout.trim();
}

export interface CommitResult {
  readonly sha: string;
  readonly message: string;
  readonly filesChanged: string[];
}

// Stages, commits, and pushes an SOP file to the current branch
export async function commitAndPushSop(
  sopFilePath: string,
  sopTitle: string,
  projectRoot: string,
): Promise<CommitResult> {
  logger.info({ sopFilePath }, "Committing SOP to repository");

  // Set git identity for the automated commit
  await git(["config", "user.name", config.GIT_AUTHOR_NAME], projectRoot);
  await git(["config", "user.email", config.GIT_AUTHOR_EMAIL], projectRoot);

  // Stage the SOP file
  await git(["add", sopFilePath], projectRoot);

  // Check if there's actually something to commit
  const status = await git(["status", "--porcelain"], projectRoot);
  if (!status) {
    logger.info("No changes to commit — SOP already exists with same content");
    const sha = await git(["rev-parse", "HEAD"], projectRoot);
    return { sha, message: "no-op", filesChanged: [] };
  }

  const commitMessage = `docs(sop): ${sopTitle}

Auto-generated by AI DevOps Platform.
Claude diagnosed a pipeline failure and produced this SOP
so the next engineer doesn't have to solve it from scratch.`;

  await git(["commit", "-m", commitMessage], projectRoot);
  const sha = await git(["rev-parse", "HEAD"], projectRoot);

  // Push to the current branch
  const branch = await git(["rev-parse", "--abbrev-ref", "HEAD"], projectRoot);
  await git(["push", "origin", branch], projectRoot);

  logger.info({ sha, branch, sopFilePath }, "SOP committed and pushed");

  return {
    sha,
    message: commitMessage,
    filesChanged: [sopFilePath],
  };
}
