import { Registry, Counter, Histogram, collectDefaultMetrics } from "prom-client";

export const registry = new Registry();

collectDefaultMetrics({ register: registry });

export const webhookRequestsTotal = new Counter({
  name: "webhook_requests_total",
  help: "Total webhook requests received",
  labelNames: ["event_type", "status"] as const,
  registers: [registry],
});

export const webhookDurationSeconds = new Histogram({
  name: "webhook_duration_seconds",
  help: "Webhook processing duration in seconds",
  labelNames: ["event_type"] as const,
  buckets: [0.05, 0.1, 0.25, 0.5, 1, 2.5, 5],
  registers: [registry],
});

export const sopGeneratedTotal = new Counter({
  name: "sop_generated_total",
  help: "Total SOPs generated by Claude",
  labelNames: ["category"] as const,
  registers: [registry],
});

export const prReviewsTotal = new Counter({
  name: "pr_reviews_total",
  help: "Total PR reviews completed",
  labelNames: ["passed"] as const,
  registers: [registry],
});
